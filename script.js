function getTranslation(key) {
    const keys = key.split('.');
    let value = translations.en;

    for (const k of keys) {
        if (value && typeof value === 'object' && k in value) {
            value = value[k];
        } else {
            return null;
        }
    }

    return typeof value === 'string' ? value : null;
}

function validationMessage(key) {
    return getTranslation(`form.validation.${key}`) || '';
}

// ============================================
// Smooth Scrolling for Anchor Links
// ============================================

document.addEventListener('DOMContentLoaded', function() {
    // Top nav mobile menu toggle
    const navToggle = document.getElementById('navToggle');
    const navLinks = document.getElementById('navLinks');
    if (navToggle && navLinks) {
        navToggle.addEventListener('click', function() {
            const isOpen = navLinks.classList.toggle('is-open');
            navToggle.setAttribute('aria-expanded', isOpen);
        });

        document.addEventListener('click', function(e) {
            if (!navLinks.classList.contains('is-open')) return;
            if (!navToggle.contains(e.target) && !navLinks.contains(e.target)) {
                closeMobileNav();
            }
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape') closeMobileNav();
        });
    }

    function closeMobileNav() {
        if (navLinks) navLinks.classList.remove('is-open');
        if (navToggle) navToggle.setAttribute('aria-expanded', 'false');
    }

    // Active nav link on scroll
    const navSectionLinks = document.querySelectorAll('.nav-links a[href^="#"]');
    const sectionIds = Array.from(navSectionLinks)
        .map((link) => link.getAttribute('href').slice(1))
        .filter(Boolean);

    if (sectionIds.length && 'IntersectionObserver' in window) {
        const sectionObserver = new IntersectionObserver(
            (entries) => {
                entries.forEach((entry) => {
                    if (!entry.isIntersecting) return;
                    const id = entry.target.id;
                    navSectionLinks.forEach((link) => {
                        const isActive = link.getAttribute('href') === `#${id}`;
                        link.classList.toggle('nav-link-active', isActive);
                    });
                });
            },
            { rootMargin: '-40% 0px -50% 0px', threshold: 0 }
        );
        sectionIds.forEach((id) => {
            const el = document.getElementById(id);
            if (el) sectionObserver.observe(el);
        });
    }

    // Floating WhatsApp FAB — show after scrolling past hero
    const whatsappFab = document.getElementById('whatsappFab');
    const heroSection = document.getElementById('hero');

    if (whatsappFab && heroSection) {
        const updateFab = () => {
            const heroBottom = heroSection.getBoundingClientRect().bottom;
            whatsappFab.hidden = heroBottom > 0;
        };
        updateFab();
        window.addEventListener('scroll', updateFab, { passive: true });
    }

    // Nav shadow on scroll
    const topNav = document.getElementById('topNav');
    if (topNav) {
        const onNavScroll = () => {
            topNav.classList.toggle('is-scrolled', window.scrollY > 8);
        };
        onNavScroll();
        window.addEventListener('scroll', onNavScroll, { passive: true });
    }

    // Sticky mobile CTA — show after hero, hide near form/footer
    const mobileCtaBar = document.getElementById('mobileCtaBar');
    const getStartedSection = document.getElementById('get-started');

    if (mobileCtaBar && heroSection) {
        const updateMobileCta = () => {
            const heroBottom = heroSection.getBoundingClientRect().bottom;
            let hideNearForm = false;

            if (getStartedSection) {
                const formTop = getStartedSection.getBoundingClientRect().top;
                hideNearForm = formTop < window.innerHeight * 0.85;
            }

            const shouldShow = heroBottom < 0 && !hideNearForm && window.innerWidth < 900;
            mobileCtaBar.hidden = !shouldShow;
            document.body.classList.toggle('has-mobile-cta', shouldShow);
        };

        updateMobileCta();
        window.addEventListener('scroll', updateMobileCta, { passive: true });
        window.addEventListener('resize', updateMobileCta, { passive: true });
    }

    // Handle smooth scrolling for anchor links
    const anchorLinks = document.querySelectorAll('a[href^="#"]');
    const fixedNavOffset = document.getElementById('topNav') ? 56 : 0;

    anchorLinks.forEach(link => {
        link.addEventListener('click', function(e) {
            const href = this.getAttribute('href');

            // Skip if it's just "#"
            if (href === '#' || href === '#!') {
                e.preventDefault();
                return;
            }

            const targetId = href.substring(1);
            const targetElement = document.getElementById(targetId);

            if (targetElement) {
                e.preventDefault();
                closeMobileNav();

                const targetPosition = targetElement.getBoundingClientRect().top + window.scrollY - fixedNavOffset;

                window.scrollTo({
                    top: targetPosition,
                    behavior: 'smooth'
                });
            }
        });
    });
    
    // ============================================
    // Form Handling (WhatsApp)
    // ============================================
    
    const signupForm = document.getElementById('signupForm');
    
    if (signupForm) {
        signupForm.addEventListener('submit', function(e) {
            e.preventDefault();
            
            const formData = new FormData(this);
            const data = Object.fromEntries(formData);
            
            if (!validateForm(data)) {
                return;
            }

            const submitBtn = document.getElementById('submitBtn');
            if (submitBtn) submitBtn.classList.add('is-loading');

            // Open WhatsApp with pre-filled message
            const whatsappNumber = '16086081288';
            const messageLines = [
                'New Biashara-Assistant signup request:',
                `Business Name: ${data.businessName || ''}`,
                `Your Name: ${data.yourName || ''}`,
                `Business Phone / WhatsApp Number: ${data.phone || ''}`,
                `Business Type: ${data.businessType || ''}`,
                `Email: ${data.email || ''}`,
                '',
                `Additional Info: ${data.additionalInfo || 'N/A'}`
            ];
            const whatsappText = messageLines.join('\n');
            const whatsappUrl = `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(whatsappText)}`;
            window.open(whatsappUrl, '_blank');

            if (submitBtn) submitBtn.classList.remove('is-loading');
            showFormSuccess();
            this.reset();
        });
    }
    
    // ============================================
    // Form Validation
    // ============================================
    
    function validateForm(data) {
        let isValid = true;
        
        // Validate required fields
        const requiredFields = ['businessName', 'yourName', 'phone', 'businessType', 'email'];
        
        requiredFields.forEach(fieldName => {
            const field = document.querySelector(`[name="${fieldName}"]`);
            
            if (!data[fieldName] || data[fieldName].trim() === '') {
                isValid = false;
                showFieldError(field, validationMessage('required'));
            } else {
                clearFieldError(field);
            }
        });
        
        // Validate email format
        const emailField = document.querySelector('[name="email"]');
        if (data.email && !isValidEmail(data.email)) {
            isValid = false;
            showFieldError(emailField, validationMessage('email'));
        }
        
        // Validate phone format (basic international phone validation)
        const phoneField = document.querySelector('[name="phone"]');
        if (data.phone && !isValidPhone(data.phone)) {
            isValid = false;
            showFieldError(phoneField, validationMessage('phone'));
        }
        
        return isValid;
    }
    
    function isValidEmail(email) {
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        return emailRegex.test(email);
    }
    
    function isValidPhone(phone) {
        const cleaned = phone.replace(/[\s\-()]/g, '');
        const phoneRegex = /^\+?\d{7,15}$/;
        return phoneRegex.test(cleaned);
    }
    
    function showFieldError(field, message) {
        if (!field) return;
        
        // Remove existing error
        clearFieldError(field);
        
        // Add error class
        field.classList.add('error');
        
        // Create error message element
        const errorElement = document.createElement('span');
        errorElement.className = 'field-error';
        errorElement.textContent = message;
        
        // Insert after field
        field.parentNode.appendChild(errorElement);
    }
    
    function clearFieldError(field) {
        if (!field) return;
        
        field.classList.remove('error');
        
        // Remove existing error message
        const existingError = field.parentNode.querySelector('.field-error');
        if (existingError) {
            existingError.remove();
        }
    }
    
    // ============================================
    // Show Form Success Message
    // ============================================
    
    function showFormSuccess() {
        const form = document.getElementById('signupForm');
        const existing = form.querySelector('.form-success');
        if (existing) existing.remove();

        const successMessage = document.createElement('div');
        successMessage.className = 'form-success';
        successMessage.setAttribute('role', 'status');
        successMessage.innerHTML = `
            <div class="form-success-inner">
                <div class="form-success-icon" aria-hidden="true">✅</div>
                <h3 class="form-success-title">${getTranslation('form.success.title')}</h3>
                <p class="form-success-text">${getTranslation('form.success.text')}</p>
            </div>
        `;
        
        form.insertBefore(successMessage, form.firstChild);
        successMessage.scrollIntoView({ behavior: 'smooth', block: 'center' });
        
        setTimeout(() => {
            successMessage.remove();
        }, 8000);
    }
    
    // ============================================
    // Real-time Field Validation
    // ============================================
    
    const formFields = document.querySelectorAll('#signupForm input, #signupForm select, #signupForm textarea');
    
    formFields.forEach(field => {
        field.addEventListener('blur', function() {
            const fieldName = this.name;
            const fieldValue = this.value.trim();
            
            // Clear previous errors
            clearFieldError(this);
            
            // Validate on blur
            if (this.hasAttribute('required') && !fieldValue) {
                showFieldError(this, validationMessage('required'));
                return;
            }
            
            // Email validation
            if (fieldName === 'email' && fieldValue && !isValidEmail(fieldValue)) {
                showFieldError(this, validationMessage('email'));
                return;
            }
            
            // Phone validation
            if (fieldName === 'phone' && fieldValue && !isValidPhone(fieldValue)) {
                showFieldError(this, validationMessage('phone'));
                return;
            }
        });
        
        // Clear error on input
        field.addEventListener('input', function() {
            if (this.classList.contains('error')) {
                clearFieldError(this);
            }
        });
    });
    
    // ============================================
    // Add CSS for error states
    // ============================================
    
    const style = document.createElement('style');
    style.textContent = `
        .form-group input.error,
        .form-group select.error,
        .form-group textarea.error {
            border-color: #EF4444;
            box-shadow: 0 0 0 3px rgba(239, 68, 68, 0.1);
        }
        .field-error {
            color: #EF4444;
            font-size: 12px;
            margin-top: 4px;
            display: block;
        }
    `;
    document.head.appendChild(style);
    
    // ============================================
    // Scroll Reveal (Intersection Observer)
    // ============================================
    const revealEls = document.querySelectorAll('.reveal, .reveal-stagger');
    if (revealEls.length && 'IntersectionObserver' in window) {
        const revealObserver = new IntersectionObserver(
            (entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('is-visible');
                        revealObserver.unobserve(entry.target);
                    }
                });
            },
            { threshold: 0.15, rootMargin: '0px 0px -40px 0px' }
        );
        revealEls.forEach((el) => revealObserver.observe(el));
    } else {
        // Fallback: show everything immediately
        revealEls.forEach((el) => el.classList.add('is-visible'));
    }
});
